#!/usr/bin/env python3
"""Generate core/fido2/cryptick_attestation.inc for Cryptick Token product.

  pip install cryptography
  python3 scripts/generate_attestation.py

Honest: self-signed Cryptick Token batch attestation (P-256), not a public CA.
USB product string and cert CN: "Cryptick Token". Manufacturer O: Ucaselabs.
"""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
from pathlib import Path
import uuid

from cryptography import x509
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.serialization import Encoding
from cryptography.x509.oid import NameOID


def c_array(name: str, data: bytes) -> str:
    lines = [f"static const uint8_t {name}[] = {{"]
    for i in range(0, len(data), 12):
        chunk = data[i : i + 12]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    out_h = root / "core" / "fido2" / "cryptick_attestation.inc"

    key = ec.generate_private_key(ec.SECP256R1())
    priv = key.private_numbers().private_value.to_bytes(32, "big")
    # Stable product AAGUID for Cryptick Token v1 (do not rotate casually)
    aaguid = uuid.UUID("c7a5e1e0-7c4b-4f0a-9d2e-55c41c710001")

    subject = issuer = x509.Name(
        [
            x509.NameAttribute(NameOID.COUNTRY_NAME, "US"),
            x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Ucaselabs"),
            x509.NameAttribute(
                NameOID.ORGANIZATIONAL_UNIT_NAME, "Cryptick Token Attestation"
            ),
            x509.NameAttribute(NameOID.COMMON_NAME, "Cryptick Token"),
        ]
    )
    now = datetime.now(timezone.utc)
    # not_before far in the past so host/browser clocks slightly off still accept
    # the cert during U2F_REGISTER signature checks.
    not_before = datetime(2020, 1, 1, tzinfo=timezone.utc)
    cert = (
        x509.CertificateBuilder()
        .subject_name(subject)
        .issuer_name(issuer)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(not_before)
        .not_valid_after(now + timedelta(days=3650 * 2))
        .add_extension(
            x509.BasicConstraints(ca=False, path_length=None), critical=True
        )
        .add_extension(
            x509.KeyUsage(
                digital_signature=True,
                content_commitment=False,
                key_encipherment=False,
                data_encipherment=False,
                key_agreement=False,
                key_cert_sign=False,
                crl_sign=False,
                encipher_only=False,
                decipher_only=False,
            ),
            critical=True,
        )
        .sign(key, hashes.SHA256())
    )
    der = cert.public_bytes(Encoding.DER)

    content = f"""/* Auto-generated by scripts/generate_attestation.py — do not edit by hand.
 * Product name: Cryptick Token
 * Manufacturer: Ucaselabs
 * Type: self-signed Cryptick Token batch attestation (P-256). Not a public CA.
 * AAGUID: {aaguid}
 * Cert serial: {cert.serial_number}
 * Subject: CN=Cryptick Token, O=Ucaselabs, OU=Cryptick Token Attestation
 */

#ifndef CRYPTICK_ATTESTATION_INC
#define CRYPTICK_ATTESTATION_INC

{c_array("kCryptickTokenAttestKey", priv)}

{c_array("kCryptickTokenAttestCertDer", der)}

static const uint8_t kCryptickTokenAaguid[16] = {{
    {', '.join(f'0x{b:02x}' for b in aaguid.bytes)}
}};

#endif /* CRYPTICK_ATTESTATION_INC */
"""
    out_h.write_text(content)
    print(f"Wrote {out_h} cert_len={len(der)} CN=Cryptick Token")


if __name__ == "__main__":
    main()
